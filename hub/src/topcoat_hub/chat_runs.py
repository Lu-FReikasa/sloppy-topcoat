"""Answers that outlive the browser (E3-07 D1, ARCHITECTURE D39).

An answer is generated by a **task of the hub**, one per answer, not inside the request that asked
for it. The task writes what it produces — events for whoever listens, the text so far into the
database every second, the result at the end — and the SSE response is only a *subscriber*: it
replays the events of the run from an offset and then follows it. Closing the stream (another tab,
a reload, a lost connection, a navigation) therefore ends nothing; a subscriber can attach again
with the message id and the number of events it already has (:meth:`AnswerRun.subscribe`), as many
at once as there are tabs. "Stop" is its own call (:meth:`AnswerRuns.stop`). The memory extraction
after the answer and the agent check before it run inside the same task and continue, too.

A hub that goes down in the middle of an answer ends its runs first (:meth:`AnswerRuns.shutdown`:
the partial text is stored with the status ``interrupted``); one that is killed leaves a message
with the status ``running`` that the next start marks ``interrupted`` (:func:`sweep_interrupted`).
A finished run stays in memory for a few minutes so that a tab that comes back right after the end
still gets the events; after that (or after a restart) the stored message is the answer.
"""

import asyncio
import json
import logging
import time
import uuid
from collections.abc import AsyncIterator, Awaitable, Callable
from typing import Any

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from topcoat_hub.gateway import spawn

log = logging.getLogger(__name__)

KEEP_SECONDS = 300.0  # a finished run stays available to late subscribers this long
KEEPALIVE_SECONDS = 20.0  # a quiet run (a long check) still sends a comment now and then
FLUSH_SECONDS = 1.0  # how often the text so far is written to the database


class AnswerRun:
    """One answer being generated: its events (as SSE chunks), its state, its task."""

    def __init__(
        self, user_id: uuid.UUID, conversation_id: uuid.UUID, message_id: int, turn: Any
    ) -> None:
        self.user_id = user_id
        self.conversation_id = conversation_id
        self.message_id = message_id
        self.aliases: set[int] = set()
        self.turn = turn
        self.events: list[str] = []
        self.finished = False
        self.stop_requested = False
        self.cancelled = False
        self.task: asyncio.Future[None] | None = None
        self.final_message: dict[str, Any] | None = None
        self.text = ""  # the answer text so far, as the subscribers saw it (for the saved copy)
        # the check (agent task) of this answer while it runs: the one the person can steer (E7-01)
        self.agent_task_id: uuid.UUID | None = None
        self.saved_at = 0.0
        self._changed = asyncio.Event()

    def publish(self, chunk: str) -> None:
        self.events.append(chunk)
        self._wake()

    def _wake(self) -> None:
        old, self._changed = self._changed, asyncio.Event()
        old.set()

    async def subscribe(
        self, offset: int = 0, keepalive: float = KEEPALIVE_SECONDS
    ) -> AsyncIterator[str]:
        """The events from ``offset`` on, then the live ones, until the run is over. A subscriber
        that goes away stops nothing; one that comes back asks for the offset it has reached."""
        i = max(offset, 0)
        while True:
            changed = self._changed  # taken before the look, so nothing is missed in between
            while i < len(self.events):
                yield f"id: {i}\n{self.events[i]}"
                i += 1
            if self.finished:
                return
            try:
                await asyncio.wait_for(changed.wait(), keepalive)
            except TimeoutError:
                yield ": keepalive\n\n"


def _delta_of(chunk: str) -> tuple[str, str]:
    """``("delta", text)`` / ``("discard", "")`` for the chunks that change the answer text."""
    if chunk.startswith("event: delta\n"):
        try:
            payload = chunk.split("data: ", 1)[1].split("\n", 1)[0]
            return "delta", str(json.loads(payload).get("text", ""))
        except (IndexError, ValueError):
            return "", ""
    if chunk.startswith("event: discard\n"):
        return "discard", ""
    return "", ""


class AnswerRuns:
    def __init__(
        self,
        sessionmaker: async_sessionmaker[AsyncSession],
        keep_seconds: float = KEEP_SECONDS,
    ) -> None:
        self.sessionmaker = sessionmaker
        self.keep_seconds = keep_seconds
        self._by_message: dict[int, AnswerRun] = {}

    def live(self, message_id: int) -> AnswerRun | None:
        return self._by_message.get(message_id)

    def alias(self, run_key: int | None, message_id: int) -> None:
        """A run that writes several messages (E3-07 D3: confirmation, report card, closing
        bubble) is found under each of them: a reload that sees the closing bubble ``running``
        attaches to the same run."""
        run = self._by_message.get(run_key) if run_key is not None else None
        if run is not None:
            self._by_message[message_id] = run
            run.aliases.add(message_id)

    def running(self, conversation_id: uuid.UUID) -> AnswerRun | None:
        return next(
            (
                r
                for r in self._by_message.values()
                if r.conversation_id == conversation_id and not r.finished
            ),
            None,
        )

    def start(
        self,
        run: AnswerRun,
        body: AsyncIterator[str],
        *,
        save: Callable[[AnswerRun, str], Awaitable[None]],
        finalize: Callable[[AnswerRun], Awaitable[dict[str, Any] | None]],
    ) -> AnswerRun:
        """Run ``body`` (the generator of the answer) as a task of the hub. ``save(run, text)``
        writes the text so far; ``finalize(run)`` settles the message if the body did not (a stop,
        a crash) and returns it for the subscribers."""
        self._by_message[run.message_id] = run
        run.aliases.add(run.message_id)
        run.task = spawn(self._drive(run, body, save, finalize))
        return run

    async def _drive(
        self,
        run: AnswerRun,
        body: AsyncIterator[str],
        save: Callable[[AnswerRun, str], Awaitable[None]],
        finalize: Callable[[AnswerRun], Awaitable[dict[str, Any] | None]],
    ) -> None:
        try:
            async for chunk in body:
                run.publish(chunk)
                kind, piece = _delta_of(chunk)
                if kind == "delta":
                    run.text += piece
                elif kind == "discard":
                    run.text = ""
                if kind and time.monotonic() - run.saved_at >= FLUSH_SECONDS:
                    run.saved_at = time.monotonic()
                    try:
                        await save(run, run.text)
                    except Exception:
                        log.exception("chat: could not save the text so far")
        except asyncio.CancelledError:
            # stopped by the user or by the hub going down. If the cancellation hit between two
            # events the body is suspended at a ``yield``: close it, so that what it was saying is
            # stored (a generator does not hear of a cancellation of its reader otherwise)
            run.cancelled = True
            aclose = getattr(body, "aclose", None)
            if aclose is not None:
                try:
                    await aclose()
                except Exception:
                    log.exception("chat: could not close the answer")
        except Exception:
            log.exception("chat: the answer failed")
            run.publish(
                _error_chunk("internal_error", "the answer could not be completed; see the hub log")
            )
        finally:
            try:
                run.final_message = await finalize(run)
            except Exception:
                log.exception("chat: could not settle the answer")
            if run.cancelled:
                run.publish(
                    "event: stopped\ndata: "
                    + json.dumps(
                        {
                            "message": run.final_message,
                            "interrupted": bool(getattr(run.turn, "interrupted", False)),
                        },
                        separators=(",", ":"),
                    )
                    + "\n\n"
                )
            run.finished = True
            run._wake()
            self._forget_later(run)

    def _forget_later(self, run: AnswerRun) -> None:
        loop = asyncio.get_running_loop()
        for message_id in run.aliases:
            loop.call_later(self.keep_seconds, self._by_message.pop, message_id, None)

    async def stop(self, user_id: uuid.UUID, message_id: int, wait: float = 10.0) -> bool:
        """Stop a running answer of this user: ``False`` if there is none. Returns when the
        partial text is stored."""
        run = self._by_message.get(message_id)
        if run is None or run.user_id != user_id or run.finished or run.task is None:
            return False
        run.stop_requested = True
        run.task.cancel()
        await asyncio.wait({run.task}, timeout=wait)
        return True

    async def stop_conversation(
        self, user_id: uuid.UUID, conversation_id: uuid.UUID, wait: float = 10.0
    ) -> bool:
        """Stop the answer being generated in one of the user's conversations (the reader that has
        not seen the message id yet — the model is still reading the prompt — can name only
        this)."""
        run = self.running(conversation_id)
        if run is None or run.user_id != user_id:
            return False
        return await self.stop(user_id, run.message_id, wait)

    async def shutdown(self, grace: float = 5.0) -> int:
        """The hub goes down: every running answer ends as ``interrupted`` (its text so far is
        stored), nothing is dropped in the middle of a query."""
        runs = [r for r in self._by_message.values() if not r.finished and r.task is not None]
        for run in runs:
            run.turn.interrupted = True
            assert run.task is not None  # noqa: S101
            run.task.cancel()
        if runs:
            await asyncio.wait({r.task for r in runs if r.task}, timeout=grace)
        return len(runs)


def _error_chunk(code: str, message: str) -> str:
    return f"event: error\ndata: {json.dumps({'code': code, 'message': message})}\n\n"


async def sweep_interrupted(sessionmaker: async_sessionmaker[AsyncSession]) -> int:
    """At startup: an answer that was running when the hub died is ``interrupted`` (its text so
    far is kept; "Continue" can go on with it). The progress line of a check that was running
    (E3-07 D3) becomes the interrupted bubble of that check: nothing may show a tool as running
    that no longer is."""
    async with sessionmaker() as db:
        await db.execute(
            text(
                "UPDATE messages SET kind = 'say', status = 'interrupted', content = '' "
                "WHERE role = 'assistant' AND kind = 'progress'"
            )
        )
        result = await db.execute(
            text(
                "UPDATE messages SET status = 'interrupted' "
                "WHERE role = 'assistant' AND status = 'running'"
            )
        )
        await db.commit()
        return int(result.rowcount or 0)  # type: ignore[attr-defined]
