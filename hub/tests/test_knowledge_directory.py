def test_the_parser_reads_every_form_of_a_reference() -> None:
    text = """# Title
## alpha
aliases: first, `second one`
- `a/b.md:120-180` Docker stack
- c.md (Zeile 7–9)
- d.md Z. 4
- e.md § Setup steps
- f.md
- `g.txt:15`
### beta
- note.md lines 2-3
- name -> x.md:1-4, y/z.md
- **gamma** → q.md:9-10
```
## in a fence
- hidden.md
```
## empty entry
"""
    entries = {e.name: e for e in kdir.parse(text)}
    assert set(entries) == {"alpha", "beta", "name", "gamma"}  # no refs: no entry, fences skipped
    alpha = entries["alpha"]
    assert alpha.aliases == ["first", "second one"]
    assert [(r.path, r.start, r.end) for r in alpha.refs] == [
        ("a/b.md", 120, 180),
        ("c.md", 7, 9),
        ("d.md", 4, None),
        ("e.md", None, None),
        ("f.md", None, None),
        ("g.txt", 15, None),
    ]
    assert alpha.refs[0].label == "Docker stack" and alpha.refs[3].label == "Setup steps"
    assert [(r.path, r.start, r.end) for r in entries["beta"].refs] == [("note.md", 2, 3)]
    assert [(r.path, r.start, r.end) for r in entries["name"].refs] == [
        ("x.md", 1, 4),
        ("y/z.md", None, None),
    ]
    assert entries["gamma"].refs[0].path == "q.md"


def test_the_parser_drops_unsafe_paths() -> None:
    entries = kdir.parse(
        "## x\n- ../secret.md:1-2\n- /etc/shadow.md\n- a/../../b.md\n- ok/a.md:1\n"
    )
    assert [r.path for r in entries[0].refs] == ["ok/a.md"]


def test_matching_takes_whole_words_and_the_most_specific_name_first() -> None:
    entries = kdir.parse(
        "## nas\n- a.md\n## nas-backup\naliases: backup box\n- b.md\n## ab\n- c.md\n## docker host\n- d.md\n"
    )
    names = lambda q: [e.name for e in kdir.match(entries, q)]  # noqa: E731
    assert names("what is on the NAS?") == ["nas"]
    assert names("is the nas-backup done") == ["nas-backup"]  # not also "nas": a hyphen joins words
    assert names("the backup box is down") == ["nas-backup"]
    assert names("nasty problem with the ab") == []  # a part of a word, and too short a name
    assert names("restart the Docker Host and the nas") == ["docker host", "nas"]
    assert len(kdir.match(entries, "nas docker host backup box", limit=2)) == 2


def test_a_section_is_cut_by_lines_by_heading_or_from_the_start() -> None:
    text = "# T\nintro\n## One\nl4\nl5\n## Two\nl7\nl8\n### Sub\nl10\n## Three\nl12\n"
    assert kdir.section(text, kdir.Ref("t.md", 4, 5)) == ("One", "l4\nl5")
    assert kdir.section(text, kdir.Ref("t.md", 7, 20)) == (
        "Two",
        "l7\nl8\n### Sub\nl10\n## Three\nl12",
    )
    heading, body = kdir.section(text, kdir.Ref("t.md", label="two"))
    assert heading == "Two" and body == "l7\nl8\n### Sub\nl10"  # to the next heading of its level
    assert kdir.section(text, kdir.Ref("t.md", label="nothing like it"))[1].startswith("# T")
    assert kdir.section("", kdir.Ref("t.md", 1, 2)) == ("", "")
    assert kdir.section("x" * 100, kdir.Ref("t.md", 1, 1), 10)[1].endswith(" …")


def test_the_outline_gives_every_headings_section() -> None:
    text = "# T\nintro\n## One\nl4\n```\n# not a heading\n```\n## Two\nl9\n"
    assert kdir.outline(text) == [(1, "T", 1, 9), (2, "One", 3, 7), (2, "Two", 8, 9)]


def test_render_and_parse_round_trip() -> None:
    entries = [
        kdir.Entry(
            "web-stack", ["webstack"], [kdir.Ref("a.md", 3, 9, "Restart"), kdir.Ref("b.md")]
        ),
        kdir.Entry("nas", [], [kdir.Ref("n.md", 5, None, "")]),
    ]
    text = kdir.render(entries, "2026-01-01", "notes")
    assert "generated by scripts/dev/make_kb_index.py on 2026-01-01 from notes" in text
    assert kdir.parse(text) == entries


