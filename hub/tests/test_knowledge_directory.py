class FakeGateway:
    def __init__(self) -> None:
        self.models: list[dict[str, Any]] = []
        self.fail = False
        self.policy = NodePolicy()

    async def list_models(self) -> list[dict[str, Any]]:
        if self.fail:
            raise RuntimeError("no node")
        return self.models

    async def embeddings(self, *a: Any, **k: Any) -> Any:  # pragma: no cover - not reached
        raise AssertionError


def test_the_embedder_becomes_bge_m3_when_it_is_served_and_never_goes_back() -> None:
    gateway = FakeGateway()
    auto = AutoEmbedder(gateway)  # type: ignore[arg-type]
    switched: list[str] = []

    async def on_switch(name: str) -> None:
        switched.append(name)

    auto.on_switch = on_switch
    before = auto.id
    assert before.startswith("hashing") and isinstance(auto._current, HashingEmbedder)

    assert asyncio.run(auto.refresh()) is None  # no model served yet
    gateway.fail = True
    assert asyncio.run(auto.refresh()) is None and auto.id == before  # a failing gateway: stay
    gateway.fail = False
    gateway.models = [{"id": "qwen-7b"}, {"id": "Some/BGE-M3-GGUF"}]
    assert asyncio.run(auto.refresh()) == "Some/BGE-M3-GGUF"
    assert switched == ["Some/BGE-M3-GGUF"] and auto.switched_to == "Some/BGE-M3-GGUF"
    assert isinstance(auto._current, GatewayEmbedder) and auto.id != before
    assert auto.id == auto._current.id
    gateway.models = []  # the node goes away: the model stays chosen, callers handle the error
    assert asyncio.run(auto.refresh()) is None and auto.id == auto._current.id
    assert switched == ["Some/BGE-M3-GGUF"]  # once


def test_the_embedding_model_chosen_in_the_gui_wins_over_the_first_bge_m3() -> None:
    gateway = FakeGateway()
    gateway.models = [{"id": "bge-m3-FP16"}, {"id": "bge-m3-q8_0"}]
    auto = AutoEmbedder(gateway)  # type: ignore[arg-type]
    switched: list[str] = []

    async def on_switch(name: str) -> None:
        switched.append(name)

    auto.on_switch = on_switch
    assert asyncio.run(auto.refresh()) == "bge-m3-FP16"
    gateway.policy = NodePolicy(embedding_model="bge-m3-q8_0")
    assert asyncio.run(auto.refresh()) == "bge-m3-q8_0"
    assert isinstance(auto._current, GatewayEmbedder) and auto._current.model == "bge-m3-q8_0"
    assert asyncio.run(auto.refresh()) is None  # once
    assert switched == ["bge-m3-FP16", "bge-m3-q8_0"]


def test_a_chosen_embedding_model_that_is_not_served_changes_nothing_yet() -> None:
    gateway = FakeGateway()
    gateway.policy = NodePolicy(embedding_model="bge-m3-q8_0")
    gateway.models = [{"id": "bge-m3-FP16"}]
    auto = AutoEmbedder(gateway)  # type: ignore[arg-type]
    before = auto.id
    assert asyncio.run(auto.refresh()) is None and auto.id == before
    gateway.models.append({"id": "bge-m3-q8_0"})
    assert asyncio.run(auto.refresh()) == "bge-m3-q8_0"


def test_the_switch_survives_a_failing_follow_up() -> None:
    gateway = FakeGateway()
    gateway.models = [{"id": "bge-m3"}]
    auto = AutoEmbedder(gateway)  # type: ignore[arg-type]

    async def broken(_name: str) -> None:
        raise RuntimeError("boom")

    auto.on_switch = broken
    assert asyncio.run(auto.refresh()) == "bge-m3" and auto.switched_to == "bge-m3"


def test_make_embedder_picks_the_configured_one_the_auto_one_or_the_transitional_one() -> None:
    gateway: Any = FakeGateway()
    assert isinstance(make_embedder(gateway, "my-embed"), GatewayEmbedder)
    assert isinstance(make_embedder(gateway, ""), AutoEmbedder)
    assert isinstance(make_embedder(gateway, "", auto=False), HashingEmbedder)


def test_the_watch_task_ends_after_the_switch() -> None:
    gateway = FakeGateway()
    auto = AutoEmbedder(gateway)  # type: ignore[arg-type]

    async def run() -> None:
        task = asyncio.create_task(auto.watch(interval=0.01))
        await asyncio.sleep(0.05)
        assert not task.done()
        gateway.models = [{"id": "bge-m3"}]
        await asyncio.wait_for(task, 2)

    asyncio.run(run())
    assert auto.switched_to == "bge-m3"


