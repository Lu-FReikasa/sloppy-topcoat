def test_the_directory_names_only_what_the_node_listed_and_the_hub_allows(
    client: TestClient, world: dict[str, Any]
) -> None:
    docs = with_directory(world)
    docs.also_list = ["SENSIBEL/logins.md"]
    docs.files["SENSIBEL/logins.md"] = "# never\nthe word traps and admin password: hunter2hunter2"
    indexed(client, world)
    docs.reads.clear()
    hits = search(client, "what about the traps")
    assert [h for h in hits if h["via"] == "directory"] == []
    assert "SENSIBEL/logins.md" not in docs.reads and "../etc/passwd.md" not in docs.reads
    assert "/etc/shadow.md" not in docs.reads
    # a note of the directory that the hub's own list excludes later is not returned either
    client.app.state.settings.knowledge_exclude = "servers"
    assert not [h for h in search(client, "web-stack") if h["path"].startswith("servers/")]


