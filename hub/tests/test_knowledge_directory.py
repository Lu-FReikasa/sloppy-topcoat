def with_directory(world: dict[str, Any], text: str = DIRECTORY) -> Docs:
    docs: Docs = world["docs"]
    docs.files[kdir.DIRECTORY_FILE] = text
    docs.files["ops.md"] = (
        "# Ops\n\n## Login\n\nThe admin password is hunter2hunter2 for the router.\n\n## Other\n\nx\n"
    )
    return docs


def test_a_named_host_is_looked_up_in_the_directory_before_the_similarity_search(
    client: TestClient, world: dict[str, Any]
) -> None:
    with_directory(world)
    indexed(client, world)
    r = client.get(
        "/api/knowledge/search", headers=AUTH, params={"q": "problem with the web-stack"}
    )
    hits = r.json()["hits"]
    assert [(h["path"], h["via"]) for h in hits[:2]] == [
        ("servers/web.md", "directory"),
        ("README.md", "directory"),
    ]
    assert hits[0]["lines"] == WEB_MD_LINES["restart"] and hits[0]["entity"] == "web-stack"
    assert hits[0]["heading"] == "Web > Restart" or hits[0]["heading"] == "Restart"
    assert "raise the memory limit" in hits[0]["text"]
    assert "Certificates" not in hits[0]["text"]  # the section, not the file
    assert "03:00" in hits[1]["text"] and hits[1]["heading"] == "Backups"
    assert all(h["path"] != kdir.DIRECTORY_FILE for h in hits)  # the index is not a note


