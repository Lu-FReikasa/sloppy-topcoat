package protocol

import (
	"crypto/rand"
	"encoding/hex"
	"regexp"
)

// NewUUID returns a random RFC 4122 version 4 UUID in canonical lowercase form.
func NewUUID() string {
	var b [16]byte
	// crypto/rand.Read never returns an error on supported platforms (Go >= 1.24 panics instead).
	_, _ = rand.Read(b[:])
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	var out [36]byte
	hex.Encode(out[0:8], b[0:4])
	out[8] = '-'
	hex.Encode(out[9:13], b[4:6])
	out[13] = '-'
	hex.Encode(out[14:18], b[6:8])
	out[18] = '-'
	hex.Encode(out[19:23], b[8:10])
	out[23] = '-'
	hex.Encode(out[24:36], b[10:16])
	return string(out[:])
}

var uuidRe = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)

// IsUUID reports whether s looks like a UUID (any version).
func IsUUID(s string) bool { return uuidRe.MatchString(s) }
